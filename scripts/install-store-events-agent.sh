#!/bin/zsh
# Install (or refresh) the App Store game-day events job on this Mac (scripts/store-events/).
# Same pattern as install-podium-agent.sh — read that one for the WHY:
#  - launchd can't read ~/Documents (macOS TCC), so the agent runs a COPY in ~/.rinkhockey/store-events.
#    The copy is a snapshot: change scripts/store-events/* and re-run this to refresh it.
#  - It renders the art with the installed Google Chrome (puppeteer-core), and talks to App Store
#    Connect with ~/.appstoreconnect/private_keys/AuthKey_23CGB7K85Q.p8 (never copied anywhere).
#
#   ./scripts/install-store-events-agent.sh
set -euo pipefail

REPO="${0:A:h:h}"
SRC="$REPO/scripts/store-events"
DEST="$HOME/.rinkhockey/store-events"
LABEL="com.rinkhockeyil.store-events"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
NODE="$(command -v node || echo /opt/homebrew/bin/node)"

[[ -f "$HOME/.appstoreconnect/private_keys/AuthKey_23CGB7K85Q.p8" ]] || { echo "✗ App Store Connect API key missing"; exit 1; }
[[ -x "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" ]] || { echo "✗ Google Chrome not installed"; exit 1; }

mkdir -p "$DEST/assets"
cp "$SRC/store-events.mjs" "$SRC/card.html" "$DEST/"
cp "$SRC/assets/"* "$DEST/assets/"
# Only the four values the job needs travel with it, readable only by this user.
grep -E '^(VITE_SUPABASE_URL|VITE_SUPABASE_ANON_KEY|SUPABASE_ACCESS_TOKEN|SUPABASE_PROJECT_REF)=' "$REPO/.env" > "$DEST/.env"
chmod 600 "$DEST/.env"
[[ $(wc -l < "$DEST/.env") -eq 4 ]] || { echo "✗ .env is missing one of the 4 keys"; exit 1; }

cat > "$DEST/package.json" <<'JSON'
{ "name": "store-events-agent", "private": true, "type": "module",
  "dependencies": { "puppeteer-core": "^24" } }
JSON
(cd "$DEST" && PUPPETEER_SKIP_DOWNLOAD=1 npm install --silent --no-audit --no-fund >/dev/null)

cat > "$DEST/run.sh" <<RUNNER
#!/bin/zsh
# Generated by install-store-events-agent.sh — edit the repo copy, not this.
set -u
LOG="\$HOME/Library/Logs/store-events.log"
mkdir -p "\$(dirname "\$LOG")"
if [[ -f "\$LOG" && \$(stat -f%z "\$LOG") -gt 1048576 ]]; then
  tail -c 262144 "\$LOG" > "\$LOG.tmp" && mv "\$LOG.tmp" "\$LOG"
fi
{
  echo "──────── \$(date '+%Y-%m-%d %H:%M:%S %Z') ────────"
  cd "$DEST" || exit 1
  "$NODE" store-events.mjs --apply
  echo "exit=\$?"
} >> "\$LOG" 2>&1
RUNNER
chmod +x "$DEST/run.sh"

mkdir -p "$HOME/Library/LaunchAgents"
cat > "$PLIST" <<PLISTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/install-store-events-agent.sh. Runs the copy in ~/.rinkhockey. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array><string>/bin/zsh</string><string>$DEST/run.sh</string></array>
  <key>StartCalendarInterval</key>
  <array>
    <dict><key>Hour</key><integer>9</integer><key>Minute</key><integer>15</integer></dict>
    <dict><key>Hour</key><integer>18</integer><key>Minute</key><integer>15</integer></dict>
  </array>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/store-events.launchd.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/store-events.launchd.log</string>
</dict>
</plist>
PLISTEOF

plutil -lint "$PLIST" >/dev/null
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

echo "✓ installed to $DEST"
echo "  runs 09:15 / 18:15 (a missed run happens when the Mac wakes)"
echo "  log:  ~/Library/Logs/store-events.log"
echo "  now:  launchctl kickstart -p gui/\$(id -u)/$LABEL"
echo "  off:  launchctl bootout gui/\$(id -u)/$LABEL"
