#!/bin/zsh
# Install (or refresh) the 4K game recorder on this Mac (scripts/recorder/recorder.py).
# Same pattern as install-store-events-agent.sh — read install-podium-agent.sh for the WHY:
#  - launchd can't read ~/Documents (macOS TCC), so the agent runs a COPY in ~/.rinkhockey/recorder.
#    The copy is a snapshot: change scripts/recorder/* and re-run this to refresh it.
#  - Always on (KeepAlive): it polls stream-recorder every few seconds and pulls every live app
#    broadcast in its original quality into ~/RinkHockeyRecordings. Needs ffmpeg and the token
#    in ~/.config/rinkhockey/recorder.json (its SHA-256 is in supabase/functions/stream-recorder).
#  - The Mac must be awake: a sleeping Mac records nothing. Keep it on power during games.
#
#   ./scripts/install-recorder-agent.sh
set -euo pipefail

REPO="${0:A:h:h}"
DEST="$HOME/.rinkhockey/recorder"
LABEL="com.rinkhockeyil.recorder"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
LOG="$HOME/Library/Logs/rinkhockey-recorder.log"

[[ -f "$HOME/.config/rinkhockey/recorder.json" ]] || { echo "✗ recorder token missing (~/.config/rinkhockey/recorder.json)"; exit 1; }
[[ -x /opt/homebrew/bin/ffmpeg ]] || { echo "✗ ffmpeg missing (brew install ffmpeg)"; exit 1; }

mkdir -p "$DEST" "$HOME/RinkHockeyRecordings" "$(dirname "$LOG")"
cp "$REPO/scripts/recorder/recorder.py" "$DEST/"

mkdir -p "$HOME/Library/LaunchAgents"
cat > "$PLIST" <<PLISTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/install-recorder-agent.sh. Runs the copy in ~/.rinkhockey. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array><string>/usr/bin/python3</string><string>-u</string><string>$DEST/recorder.py</string></array>
  <key>EnvironmentVariables</key>
  <dict><key>PATH</key><string>/opt/homebrew/bin:/usr/bin:/bin</string></dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>30</integer>
  <key>StandardOutPath</key><string>$LOG</string>
  <key>StandardErrorPath</key><string>$LOG</string>
</dict>
</plist>
PLISTEOF

plutil -lint "$PLIST" >/dev/null
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

echo "✓ installed to $DEST (always on)"
echo "  saves: ~/RinkHockeyRecordings/<game>/cam<N>/*.mp4"
echo "  log:   $LOG"
echo "  off:   launchctl bootout gui/\$(id -u)/$LABEL"
